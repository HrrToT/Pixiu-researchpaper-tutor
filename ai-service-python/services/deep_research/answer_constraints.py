"""User-visible length constraints, separate from model token budgets."""
import json
import re


def resolve_evidence_aliases(report, aliases):
    """Resolve only exact IDs supplied in this prompt, never guessed hash prefixes."""
    for claim in report.get('claims', []):
        if isinstance(claim, dict) and isinstance(claim.get('evidenceRefs'), list):
            claim['evidenceRefs'] = [aliases.get(ref, ref) if isinstance(ref, str) else ref
                                     for ref in claim['evidenceRefs']]
            bindings = claim.get('tableBindings')
            for binding in bindings if isinstance(bindings, list) else []:
                if isinstance(binding, dict) and isinstance(binding.get('evidenceId'), str):
                    binding['evidenceId'] = aliases.get(binding['evidenceId'], binding['evidenceId'])
    return report


def normalize_conditions(report):
    for claim in report.get('claims', []):
        if not isinstance(claim, dict):
            continue
        conditions = claim.get('conditions')
        if isinstance(conditions, str):
            claim['conditions'] = {'context': conditions} if conditions.strip() else {}
        elif isinstance(conditions, list) and all(isinstance(value, str) for value in conditions):
            claim['conditions'] = {str(index + 1): value for index, value in enumerate(conditions)}
    return report


def requested_character_limit(question):
    from services.deep_research.request_context import ResearchQuestion
    if isinstance(question, ResearchQuestion):
        # Newest human clarification wins. Questions generated by the model
        # and their example lengths are not user instructions.
        cancel = re.compile(r'(?<!不要)(?<!不用)(?<!无需)(?<!不必)(?<!不)'
                            r'(?:(?:取消|去掉)(?:原来(?:的)?|之前(?:的)?)?字数(?:限制|上限)'
                            r'|(?:不限制|不限|无)(?:总)?字数|\bno character limit\b)', re.I)
        for layer in question.instruction_layers:
            matches = [(m.start(), min(int(m[1]), 10000)) for m in re.finditer(
                r'(\d{2,5})\s*(?:字|个字符|characters)\s*(?:以内|以下|内|maximum|max)?', layer, re.I)]
            matches += [(m.start(), None) for m in cancel.finditer(layer)]
            if matches:
                return max(matches, key=lambda row: row[0])[1]
        return None
    match = re.search(r'(\d{2,5})\s*(?:字|个字符|characters)\s*(?:以内|以下|内|maximum|max)?', question, re.I)
    return min(int(match[1]), 10000) if match else None


def answer_character_count(report):
    count = 0
    for claim in report.get('claims', []):
        if not isinstance(claim, dict) or not isinstance(claim.get('text'), str):
            return float('inf')
        conditions = claim.get('conditions') or {}
        if not isinstance(conditions, dict):
            return float('inf')
        count += len(claim['text']) + sum(len(str(key)) + len(str(value)) + 2 for key, value in conditions.items())
    return count


def _core_claims(claims, limit, output_kind, evidence):
    if output_kind != 'paper_comparison':
        return claims[:2 if limit <= 300 else 4]
    works = {e['evidenceId']: e.get('sourceWorkId') for e in evidence}
    selected, covered, joint = [], set(), None
    for claim in claims:
        identities = {works[ref] for ref in claim.get('evidenceRefs', []) if works.get(ref)}
        if len(identities) == 1 and not identities <= covered:
            selected.append(claim)
            covered.update(identities)
        elif len(identities) > 1 and claim.get('kind') == 'inference' and joint is None:
            joint = claim
    if joint is not None:
        selected.append(joint)
    return selected or claims[:3]


def visible_count(candidate, limit, output_kind='', evidence=(), presentation_version=0):
    """Use the publication layout's character measure before publishing."""
    if type(presentation_version) is not int or presentation_version not in (2,3,4):
        return answer_character_count(candidate)
    from services.deep_research.reporting import build_sections, publication_notices, visible_answer_character_count
    claims = candidate.get('claims', [])
    visible_notice, _ = publication_notices(claims, presentation_version=presentation_version,output_kind=output_kind)
    proposed = candidate.get('sections')
    return visible_answer_character_count({'presentationVersion': presentation_version, 'characterLimit': limit,
        'outputKind': output_kind, 'claims': claims, 'evidence': evidence, 'limitations': visible_notice,
        'sections': build_sections(claims, output_kind, proposed if isinstance(proposed,list) else None,
                                   presentation_version=presentation_version)})


def compact_answer(report, question, invoke, parse, *, output_kind='', evidence=(), preserve_claims=False,
                   presentation_version=0, fixed_claim_ids=(), explicit_edit_scope=False, compact_layout=False,preserve_answers=False,measured_edit_budget=False,lean_edit=False,focused_edit=False):
    if type(focused_edit) is not bool:raise ValueError('Invalid focused editing policy')
    if type(lean_edit) is not bool:raise ValueError('Invalid lean editing policy')
    if type(measured_edit_budget) is not bool:raise ValueError('Invalid measured editing policy')
    if type(preserve_answers) is not bool:raise ValueError('Invalid answer preservation policy')
    if focused_edit:preserve_answers=True
    if preserve_answers:
        preserve_claims=True
        explicit_edit_scope=True
    if type(explicit_edit_scope) is not bool:raise ValueError('Invalid explicit edit scope policy')
    if type(compact_layout) is not bool:raise ValueError('Invalid compact layout policy')
    report = normalize_conditions(report)
    limit = requested_character_limit(question)
    if not report.get('claims'):
        return report
    modern = type(presentation_version) is int and presentation_version in (2,3,4)
    def count(candidate):
        return visible_count(candidate, limit, output_kind, evidence, presentation_version)
    if not limit or count(report) <= limit:
        return report
    # Reduce the rewrite's scope, not its evidence: original references and kinds
    # are restored by code and the rewritten claims are verified afterwards.
    core = report['claims'] if preserve_claims else _core_claims(report['claims'], limit, output_kind, evidence)
    fixed_ids = set(fixed_claim_ids)
    if fixed_ids:
        selected_ids = {c.get('claimId') for c in core} | fixed_ids
        core = [c for c in report['claims'] if c.get('claimId') in selected_ids]
    fixed = [c for c in core if c.get('claimId') in fixed_ids]
    editable = [c for c in core if c.get('claimId') not in fixed_ids]
    from services.deep_research.table_bindings import bound_table_context
    content_limit = limit
    if modern:
        # Only a layout preview is blanked; source/claim inputs sent to the
        # rewrite remain intact, and the final rewrite is still reverified.
        overhead = count({**report, 'claims': [{**c, 'text': '', 'conditions': {}} for c in core]})
        overhead += len('适用条件：') * sum(bool(c.get('conditions')) for c in core)
        content_limit = max(1, limit - overhead)
    if focused_edit:
        from services.deep_research.compaction_editor import focused_fixed_ids
        fixed_ids=focused_fixed_ids(core,content_limit,fixed_ids)
        fixed=[c for c in core if c.get('claimId') in fixed_ids]
        editable=[c for c in core if c.get('claimId') not in fixed_ids]
    if fixed:
        content_limit -= answer_character_count({'claims':fixed})
        if content_limit <= 0 or not editable:
            return None  # Preserve the operator and report the limit honestly.
    inputs = [{**{key: c.get(key, {} if key == 'conditions' else '')
                   for key in ('claimId', 'text', 'conditions')},
               'requiredTableContext': bound_table_context(c, evidence)} for c in editable]
    target = max(1 if modern else 15, int(content_limit * .7 / max(1, len(editable))))
    prompt = f'''用中文压缩以下核心回答。用户问题：{question}
总共最多{content_limit}字，每条text与conditions合计尽量不超过{target}字。
只返回JSON：{{"claims":[{{"claimId":"原ID","text":"短结论","conditions":{{}}}}]}}。
不要返回引用、kind、章节或额外声明，系统保留原始身份并重新核验。
保留论断必需的实验条件、方法标签和限定词；删去旁支数字和背景。
requiredTableContext给出原引用单元格的身份：若保留该数值，必须在同条text中
保留method、group的每一层（数据集/子集/聚合列）、metric及value的对应关系。
这些字段是改写依据，不是新增结论；不在输出JSON中重复它们。
把条件写入text即可，不要在conditions重复。不能新增事实。
若面向初学者，保留“调整了什么→随后怎样变化”的普通语言解释；优先删公式和术语铺陈，
不要把因果机制缩成方法名或“梯度能流动”。只保留原回答已有的机制与限定条件。
{'必须保留每个输入ID，只缩短措辞，不合并或删除回答点。' if preserve_claims else '必须保留每个输入ID：它们分别代表各论文结论和跨论文可比性。' if output_kind == 'paper_comparison' else 'You MAY DROP 次要声明，但保留直接回答问题的判断。'}
输入：{json.dumps(inputs, ensure_ascii=False)}'''
    if fixed:
        prompt = prompt.replace('\n输入：', '\n固定范围说明（只读，已从可用字数扣除，不得返回或改写其ID）：'
            + json.dumps([{k:c.get(k) for k in ('claimId','text','conditions')} for c in fixed],ensure_ascii=False)
            + '\n输入：',1)
    if explicit_edit_scope:
        # Only editable rows carry identities. Read-only context cannot be
        # mistaken for additional response rows; code rejoins it unchanged.
        prompt = f'''你是正文编辑器。只精简下方 editableClaims，不重新回答用户的完整问题。
用户问题仅作为判断含义的背景：{question}
可编辑部分的 text 与 conditions 合计硬上限为 {content_limit} 字（标点、英文、数字均计入），
建议每条不超过 {target} 字。保留所有可编辑条目的实际判断与必要条件；不能合并、删除或增加条目。
只返回 JSON：{{"claims":[{{"claimId":"editableClaims中的原ID","text":"精简正文","conditions":{{}}}}]}}。
返回 ID 的有序列表必须恰好是 {json.dumps([c['claimId'] for c in editable],ensure_ascii=False)}。
readonlyContext 已由系统保留且从字数额度扣除；绝不能输出它。系统随后按原顺序拼回全部条目。
只精简措辞，不新增或强化事实、因果或适用范围。保留原有结论的限定程度。
requiredTableContext 是可追溯的数值依据，不是必须逐项抄写的清单。
可以省去旁支数值示例；若保留某个数值，须同时保留其方法、数据集/组别、指标及精确值身份。
保留回答中的比较判断和必要实验条件，不能用数值清单替代判断，也不能新编判断标准。
面向新手时保留原有机制解释。条件写在 text，conditions 保持为空，避免重复。
只返回上述三个字段，不输出说明、引用、kind、表格上下文或新声明。
readonlyContext：{json.dumps([{'text':c.get('text',''),'conditions':c.get('conditions',{})} for c in fixed],ensure_ascii=False)}
editableClaims：{json.dumps(inputs,ensure_ascii=False)}'''
    if compact_layout:
        from services.deep_research.short_factual_layout import PROSE_GUIDANCE as GUIDANCE
        prompt+='\n'+GUIDANCE+'\n原稿当前可见长度：'+str(count(report))+'。必须在现有硬上限内实质精简，不能只换同义词。'
    if preserve_answers:
        from services.deep_research.answer_preservation import GUIDANCE
        prompt+='\n'+GUIDANCE
    if measured_edit_budget:
        from services.deep_research.compaction_editor import budget_guidance
        prompt+=budget_guidance(inputs,content_limit)
    if lean_edit:
        from services.deep_research.compaction_editor import lean_prompt
        prompt=lean_prompt(inputs,content_limit,question,fixed)
    result = invoke(prompt)
    finish = (result.get('finishReason', result.get('finish_reason')) if isinstance(result, dict)
              else getattr(result, 'finish_reason', None))
    if finish == 'length':
        return None
    compact = parse(result.get('content', '') if isinstance(result, dict) else result.content)
    if not isinstance(compact, dict) or not isinstance(compact.get('claims'), list) or not compact['claims']:
        return None
    if preserve_answers and any(not isinstance(c,dict) or not isinstance(c.get('text'),str) or not c['text'].strip() for c in compact['claims']):return None
    if (compact_layout or preserve_answers) and (set(compact)!={'claims'} or any(not isinstance(c,dict)
            or set(c)!={'claimId','text','conditions'} or not isinstance(c.get('text'),str)
            or not isinstance(c.get('conditions'),dict) for c in compact['claims'])):
        return None
    compact = normalize_conditions(compact)
    original = {c.get('claimId'): c for c in editable if isinstance(c, dict)}
    seen = set()
    for claim in compact['claims']:
        if not isinstance(claim, dict) or claim.get('claimId') not in original or claim.get('claimId') in seen:
            return None
        seen.add(claim['claimId'])
        before = original[claim['claimId']]
        if ('kind' in claim and claim['kind'] != before.get('kind')) or ('evidenceRefs' in claim and claim['evidenceRefs'] != before.get('evidenceRefs')):
            return None
        merged = {**before, **claim}
        # Wording-only compaction cannot rewrite the evidence/measurement
        # contract. The final verifier still checks the revised prose.
        if any(key in claim and claim[key] != before.get(key)
               for key in ('tableBindings', 'obligationIds', 'executionSpec', 'designRole')):
            return None
        claim.clear()
        claim.update(merged)
    if preserve_answers and [c['claimId'] for c in compact['claims']] != [c['claimId'] for c in editable]:return None
    if (preserve_claims or output_kind == 'paper_comparison') and seen != set(original):
        return None
    if fixed:
        revised = {c['claimId']:c for c in compact['claims']}
        compact['claims'] = [c if c.get('claimId') in fixed_ids else revised[c['claimId']]
                             for c in core if c.get('claimId') in fixed_ids or c.get('claimId') in revised]
    if 'sections' not in compact and 'sections' in report:
        compact['sections'] = report['sections']
    return compact if count(compact) <= limit else None
